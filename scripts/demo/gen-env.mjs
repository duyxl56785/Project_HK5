// Generates .env.demo (git-ignored) with fresh random secrets for the local demo stack.
// Usage: node scripts/demo/gen-env.mjs [--force]
import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const target = resolve(import.meta.dirname, '../../.env.demo');
const secret = () => randomBytes(32).toString('base64url');
const authorityTokens = ['USER', 'SELLER', 'PRODUCT', 'CART', 'ORDER', 'NOTIFICATION'].map((name) => `${name}_AUTHORITY_TOKEN`);
if (existsSync(target) && !process.argv.includes('--force')) {
  const current = readFileSync(target, 'utf8');
  for (const key of authorityTokens) if (!current.includes(`${key}=`)) appendFileSync(target, `${key}=${secret()}\n`);
  console.log(`.env.demo already exists, keeping it (pass --force to regenerate and reset the DB volume).`);
  process.exit(0);
}

const values = {
  POSTGRES_PASSWORD: secret(),
  AUTH_DB_PASSWORD: secret(),
  AUTH_MIGRATION_PASSWORD: secret(),
  USER_DB_PASSWORD: secret(),
  USER_MIGRATION_PASSWORD: secret(),
  JWT_ISSUER_URI: 'http://auth-service.hk5.local',
  JWT_AUDIENCE: 'smart-ecommerce-api',
  JWT_HS256_CURRENT_KID: 'demo-key-v1',
  JWT_HS256_CURRENT_KEY_B64: randomBytes(32).toString('base64'),
  ALLOWED_ORIGINS: 'http://localhost:5173',
  // One credential per caller->callee pair (OD-09).
  ORDER_CART_TOKEN: secret(),
  ORDER_INVENTORY_TOKEN: secret(),
  ORDER_PRODUCT_TOKEN: secret(),
  ORDER_SELLER_TOKEN: secret(),
  ORDER_NOTIFICATION_TOKEN: secret(),
  CART_PRODUCT_TOKEN: secret(),
  PRODUCT_INVENTORY_TOKEN: secret(),
  PRODUCT_SELLER_TOKEN: secret(),
  PRODUCT_ORDER_TOKEN: secret(),
  SELLER_AUTH_TOKEN: secret(),
  SELLER_NOTIFICATION_TOKEN: secret(),
  ...Object.fromEntries(authorityTokens.map((key) => [key, secret()])),
  ADMIN_BOOTSTRAP_EMAIL: 'admin@hk5.local',
  ADMIN_BOOTSTRAP_PASSWORD: secret().slice(0, 20),
};

const body = ['# Generated by scripts/demo/gen-env.mjs. Local demo only, never commit.']
  .concat(Object.entries(values).map(([k, v]) => `${k}=${v}`)).join('\n') + '\n';
writeFileSync(target, body, { mode: 0o600 });
console.log(`Wrote ${target}. Admin login: ${values.ADMIN_BOOTSTRAP_EMAIL} (password in .env.demo).`);
