// Generates .env.demo (git-ignored) with fresh random secrets for the local demo stack,
// and writes each secret to docker/secrets (git-ignored), which Compose mounts as Docker secrets.
// Usage: node scripts/demo/gen-env.mjs [--force]
import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const target = resolve(import.meta.dirname, '../../.env.demo');
const secret = () => randomBytes(32).toString('base64url');
const authorityTokens = ['USER', 'SELLER', 'PRODUCT', 'CART', 'ORDER', 'NOTIFICATION'].map((name) => `${name}_AUTHORITY_TOKEN`);
// Approved for local use only by docs/project-report/M01_FINANCE_DECISION.md (MD09).
// Any other environment needs its own decision.
const localPolicy = {
  INVENTORY_ORDER_PAIR_ENABLED: 'true',
  HK5_FINANCE_POLICY_APPROVED: 'true',
  HK5_FINANCE_PLATFORM_RATE: '0.05',
  HK5_FINANCE_CURRENCY_SCALE: '0',
  HK5_FINANCE_HOUSE_EXEMPT: 'true',
};
const notSecret = new Set(['JWT_ISSUER_URI', 'JWT_AUDIENCE', 'JWT_HS256_CURRENT_KID', 'ALLOWED_ORIGINS', 'ADMIN_BOOTSTRAP_EMAIL', ...Object.keys(localPolicy)]);

function writeSecrets() {
  const env = Object.fromEntries(readFileSync(target, 'utf8').split('\n')
    .filter((line) => line.includes('=') && !line.startsWith('#'))
    .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1).trim()]));
  const directory = resolve(import.meta.dirname, '../../docker/secrets');
  mkdirSync(directory, { recursive: true });
  const write = (name, value) => writeFileSync(resolve(directory, name), value, { mode: 0o600 });
  for (const [name, value] of Object.entries(env)) if (!notSecret.has(name)) write(name, value);
  const fenced = { USER: 'user-service:8102', SELLER: 'seller-service:8103', PRODUCT: 'product-service:8104', CART: 'cart-service:8106', ORDER: 'order-service:8107', NOTIFICATION: 'notification-service:8108' };
  write('WRITE_FENCE_TARGETS', Object.entries(fenced).map(([name, host]) => `${env[`${name}_AUTHORITY_TOKEN`]}@http://${host}`).join(','));
}

if (existsSync(target) && !process.argv.includes('--force')) {
  const current = readFileSync(target, 'utf8');
  for (const key of authorityTokens) if (!current.includes(`${key}=`)) appendFileSync(target, `${key}=${secret()}\n`);
  for (const [key, value] of Object.entries(localPolicy)) if (!current.includes(`${key}=`)) appendFileSync(target, `${key}=${value}\n`);
  writeSecrets();
  console.log(`.env.demo already exists, keeping it (pass --force to regenerate and reset the DB volume).`);
  process.exit(0);
}

const values = {
  POSTGRES_PASSWORD: secret(),
  AUTH_DB_PASSWORD: secret(),
  AUTH_MIGRATION_PASSWORD: secret(),
  USER_DB_PASSWORD: secret(),
  USER_MIGRATION_PASSWORD: secret(),
  JWT_ISSUER_URI: 'http://auth-service.hk5.local',
  JWT_AUDIENCE: 'smart-ecommerce-api',
  JWT_HS256_CURRENT_KID: 'demo-key-v1',
  JWT_HS256_CURRENT_KEY_B64: randomBytes(32).toString('base64'),
  ALLOWED_ORIGINS: 'http://localhost:5173',
  // One credential per caller->callee pair (OD-09).
  ORDER_CART_TOKEN: secret(),
  ORDER_INVENTORY_TOKEN: secret(),
  ORDER_PRODUCT_TOKEN: secret(),
  ORDER_SELLER_TOKEN: secret(),
  CART_PRODUCT_TOKEN: secret(),
  PRODUCT_INVENTORY_TOKEN: secret(),
  PRODUCT_SELLER_TOKEN: secret(),
  SELLER_AUTH_TOKEN: secret(),
  SELLER_NOTIFICATION_TOKEN: secret(),
  ...Object.fromEntries(authorityTokens.map((key) => [key, secret()])),
  ...localPolicy,
  ADMIN_BOOTSTRAP_EMAIL: 'admin@hk5.local',
  ADMIN_BOOTSTRAP_PASSWORD: secret().slice(0, 20),
};

const body = ['# Generated by scripts/demo/gen-env.mjs. Local demo only, never commit.']
  .concat(Object.entries(values).map(([k, v]) => `${k}=${v}`)).join('\n') + '\n';
writeFileSync(target, body, { mode: 0o600 });
writeSecrets();
console.log(`Wrote ${target}. Admin login: ${values.ADMIN_BOOTSTRAP_EMAIL} (password in .env.demo).`);
